// Get text templates by category
export function getTextTemplatesByCategory(categoryId: string): TextTemplate[] {
  if (categoryId === "all") return TEXT_TEMPLATES
  return TEXT_TEMPLATES.filter(t => t.category === categoryId)
}

// Search text templates
export function searchTextTemplates(query: string): TextTemplate[] {
  const lowerQuery = query.toLowerCase()
  return TEXT_TEMPLATES.filter(t => 
    t.name.en.toLowerCase().includes(lowerQuery) ||
    t.name.ar.includes(query) ||
    t.preview.toLowerCase().includes(lowerQuery)
  )
}
